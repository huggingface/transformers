#!/usr/bin/env bash
# Write constraints-<arch>.txt from a built image's pip freeze.
#
# The Dockerfile installs every Python package under these constraints, so an
# image is reproducible and a dependency change is a reviewed diff, not drift.
# To move the pins (a transformers bump, a security fix):
#
#   1. build the image with the constraints file emptied (`: > constraints-<arch>.txt`)
#      so pip resolves freely;
#   2. ./constraints-update.sh <arch> <that image>
#   3. review `git diff constraints-<arch>.txt`; a major version jump is a decision;
#   4. rebuild with the new file and check that its freeze matches the file.
#
#   ./constraints-update.sh gfx1151 local/hf-unpinned-gfx1151:v5.20.2
set -euo pipefail
cd "$(dirname "$0")"
ARCH="${1:?arch, e.g. gfx1151}"
IMAGE="${2:?image to read the freeze from}"
OUT="constraints-${ARCH}.txt"

# Editable installs (transformers itself, checked out at REF) and direct URL
# references cannot be constraints; pip rejects both. The torch stack (torch,
# torchvision, torchaudio, triton, rocm*, amd-torch*) is left out: the Dockerfile's torch
# steps own it through TORCH_VERSION and /opt/rocm-constraints.txt, and a pin
# here would contradict any build that passes other torch build-args (the
# defaults are ROCm 7.14). Everything else is pinned exactly.
freeze="$(docker run --rm --entrypoint python3 "$IMAGE" -m pip freeze --all)"
{
  echo "# pip freeze of ${IMAGE} (${ARCH}), $(date -u +%Y-%m-%d)."
  echo "# Generated by constraints-update.sh; review the diff before pushing an image."
  # urllib3 is pinned on the kernels step in the Dockerfile, not here: see the
  # comment there (transformers[testing] wants <2, kernels' tuf wants ~=2.0).
  printf '%s\n' "$freeze" | grep -vE '^(-e |#)| @ ' | grep -E '==' \
    | grep -viE '^urllib3==' \
    | grep -vE '^(torch|torchvision|torchaudio|triton|rocm|rocm-sdk-[A-Za-z0-9.-]+|rocm-bootstrap|amd-torch[A-Za-z0-9.-]*)==' \
    | LC_ALL=C sort -f
} > "$OUT"
echo "wrote $OUT: $(grep -vc '^#' "$OUT") pins"
