# The audio marker is consumed by the processor, not by the text tokenizer.
QWEN3_TTS_CHAT_TEMPLATE = (
    "{%- set ns = namespace(text=none, instructions=[], audio=false) -%}"
    "{%- for message in messages -%}"
    "{%- set content = message['content'] -%}"
    "{%- if content is string -%}"
    "{%- set text = content -%}"
    "{%- else -%}"
    "{%- set text = content | selectattr('type', 'equalto', 'text') | map(attribute='text') | join(' ') -%}"
    "{%- endif -%}"
    "{%- if message['role'] in ['system', 'scene'] -%}"
    "{%- set ns.instructions = ns.instructions + [text] -%}"
    "{%- elif message['role'] == 'user' -%}"
    "{%- set ns.text = text -%}"
    "{%- set ns.audio = content is not string and "
    "content | selectattr('type', 'equalto', 'audio') | list | length > 0 -%}"
    "{%- else -%}"
    "{{- raise_exception('Unsupported message role for Qwen3TTS: ' + message['role']) -}}"
    "{%- endif -%}"
    "{%- endfor -%}"
    "{%- if ns.text is none -%}"
    "{{- raise_exception('Each conversation must contain a user message with the text to synthesize.') -}}"
    "{%- endif -%}"
    "{%- if ns.instructions -%}"
    "{{- '<|im_start|>user\\n' + ns.instructions | join(' ') + '<|im_end|>\\n' -}}"
    "{%- endif -%}"
    "{%- if ns.audio -%}{{- '<|audio|>' -}}{%- endif -%}"
    "{{- '<|im_start|>assistant\\n' + ns.text + '<|im_end|>\\n<|im_start|>assistant\\n' -}}"
)
logger = logging.get_logger(__name__)


class Qwen3TTSProcessorKwargs(ProcessingKwargs, total=False):
    """Kwargs for Qwen3TTS processor."""

    _defaults = {}


@auto_docstring
class Qwen3TTSProcessor(ProcessorMixin):
    r"""
    Constructs a Qwen3TTS processor which combines a Qwen tokenizer and a feature extractor.

    [`Qwen3TTSProcessor`] offers all the functionalities of [`Qwen3TTSFeatureExtractor`], [`Qwen2TokenizerFast`], and
    [`Qwen3TTSTokenizerModel`]. It combines the text tokenizer, the speaker feature extractor, and the
    audio tokenizer that decodes the codes generated by the model back into audio waveforms.
    See the [`~Qwen3TTSProcessor.__call__`] and [`~Qwen3TTSProcessor.decode`] for more information.

    Args:
        feature_extractor ([`Qwen3TTSFeatureExtractor`], *optional*):
            The feature extractor for extracting mel spectrogram features from audio.
        tokenizer ([`Qwen2TokenizerFast`], *optional*):
            The text tokenizer for encoding text inputs. Should be a Qwen2 tokenizer.
        chat_template (`str`, *optional*):
            The Jinja template to use for formatting conversations using the chat template.
    """

    attributes = ["feature_extractor", "tokenizer"]
    valid_processor_kwargs = Qwen3TTSProcessorKwargs
    tokenizer_class = ("Qwen2Tokenizer", "Qwen2TokenizerFast")
    audio_tokenizer_class = "Qwen3TTSTokenizerModel"

    def __init__(self, feature_extractor=None, tokenizer=None, audio_tokenizer=None, chat_template=None):
        r"""
        audio_tokenizer ([`Qwen3TTSTokenizerModel`], *optional*):
            The audio tokenizer that decodes the codes the model generates back into waveforms. A checkpoint
            records which one to use, so `from_pretrained` supplies it.
        """
        super().__init__(
            feature_extractor,
            tokenizer,
            audio_tokenizer=audio_tokenizer,
            chat_template=QWEN3_TTS_CHAT_TEMPLATE if chat_template is None else chat_template,
        )

    @auto_docstring
    def __call__(
        self,
        text=None,
        audio=None,
        audio_codes: "torch.Tensor | list[torch.Tensor] | None" = None,
        speaker_embeddings: "torch.Tensor | list[torch.Tensor] | None" = None,
        output_labels: bool = False,
        _chat_template: bool = False,
        **kwargs: Unpack[Qwen3TTSProcessorKwargs],
    ) -> BatchFeature:
        """
        Prepare inputs for the Qwen3-TTS model.

        Args:
            text (`str` or `List[str]`, *optional*):
                The text string or batch of text strings to be encoded.
            audio (`np.ndarray`, `List[float]`, `List[np.ndarray]`, *optional*):
                The audio input to extract features from. Used for speaker embedding extraction.
            audio_codes (`torch.Tensor` or `list[torch.Tensor]`, *optional*):
                Precomputed audio codes of shape `(audio_length, num_code_groups)` for one example, or a batch of
                shape `(batch_size, audio_length, num_code_groups)`. A list contains one code sequence per example.
                Requires `text` and `speaker_embeddings`; text is formatted as a non-streaming synthesis prompt.
            speaker_embeddings (`torch.Tensor` or `list[torch.Tensor]`, *optional*):
                Precomputed speaker embeddings of shape `(hidden_size,)` for one example, or
                `(batch_size, hidden_size)` for a batch. Cached training inputs require PyTorch tensor outputs.
            output_labels (`bool`, *optional*, defaults to `False`):
                Whether to return unshifted audio-code labels for cached training inputs. Padded audio frames are
                masked with `-100`. Text and audio are padded independently, with their respective attention masks.
            **kwargs:
                Additional keyword arguments passed to the tokenizer or feature extractor.

        Returns:
            BatchFeature: Dictionary containing tokenized text and/or audio features.
        """
        if _chat_template:
            # ProcessorMixin has already rendered the template and loaded/resampled the audio.
            kwargs.pop("images", None)
            kwargs.pop("videos", None)
            return self._process_chat_inputs(text, audio, output_labels=output_labels, **kwargs)
        cached_inputs = audio_codes is not None or speaker_embeddings is not None
        if output_labels and not cached_inputs:
            raise ValueError("`output_labels=True` requires cached training inputs.")
        if cached_inputs:
            requires_backends(self, ["torch"])
            if text is None or audio_codes is None or speaker_embeddings is None:
                raise ValueError("Cached training inputs require `text`, `audio_codes`, and `speaker_embeddings`.")
            if audio is not None:
                raise ValueError("Provide either cached training inputs or raw `audio`, not both.")
        elif text is None and audio is None:
            raise ValueError("You need to specify at least one of `text` or `audio` input to process.")

        output_kwargs = self._merge_kwargs(
            Qwen3TTSProcessorKwargs,
            tokenizer_init_kwargs=self.tokenizer.init_kwargs if self.tokenizer is not None else {},
            **kwargs,
        )

        data = {}
        if cached_inputs:
            text_kwargs = output_kwargs["text_kwargs"]
            if text_kwargs.get("return_tensors") not in (None, "pt"):
                raise ValueError("Cached training inputs require `return_tensors='pt'`.")
            text_kwargs["return_tensors"] = "pt"
            text_kwargs.setdefault("padding", True)
            text_kwargs["return_attention_mask"] = True

        if text is not None:
            if not isinstance(text, list):
                text = [text]
            if cached_inputs:
                if getattr(audio_codes, "ndim", None) == 2:
                    audio_codes = [audio_codes]
                audio_codes = [torch.as_tensor(codes) for codes in audio_codes]
                if len(audio_codes) != len(text) or not audio_codes:
                    raise ValueError("Provide one audio code sequence per text prompt.")
                for codes in audio_codes:
                    if codes.ndim != 2 or codes.shape[0] == 0 or codes.shape[1] == 0:
                        raise ValueError("Each audio code sequence must have shape (audio_length, num_code_groups).")
                    if codes.dtype not in (torch.int32, torch.int64):
                        raise ValueError("Audio codes must contain integer token IDs.")
                if len({codes.shape[1] for codes in audio_codes}) != 1:
                    raise ValueError("All audio code sequences must use the same number of codebooks.")
                if isinstance(speaker_embeddings, (list, tuple)):
                    speaker_embeddings = torch.stack([torch.as_tensor(embedding) for embedding in speaker_embeddings])
                else:
                    speaker_embeddings = torch.as_tensor(speaker_embeddings)
                if speaker_embeddings.ndim == 1:
                    speaker_embeddings = speaker_embeddings.unsqueeze(0)
                if speaker_embeddings.ndim != 2 or speaker_embeddings.shape[0] != len(text):
                    raise ValueError("Provide one speaker embedding per text prompt.")
                if not speaker_embeddings.is_floating_point():
                    raise ValueError("Speaker embeddings must contain floating-point values.")
                if output_kwargs["text_kwargs"].get("truncation") not in (None, False, "do_not_truncate"):
                    raise ValueError("Cached training text cannot be truncated because its prompt suffix is required.")
                text = [self._build_synthesis_text(value) for value in text]
                data["audio_codes"] = torch.nn.utils.rnn.pad_sequence(
                    [codes.long() for codes in audio_codes], batch_first=True, padding_value=0
                )
                audio_lengths = torch.tensor(
                    [codes.shape[0] for codes in audio_codes], device=data["audio_codes"].device
                )
                data["audio_attention_mask"] = (
                    torch.arange(data["audio_codes"].shape[1], device=audio_lengths.device)[None, :]
                    < audio_lengths[:, None]
                ).long()
                data["speaker_embeddings"] = speaker_embeddings
                if output_labels:
                    data["labels"] = data["audio_codes"].clone()
                    data["labels"].masked_fill_(~data["audio_attention_mask"].bool()[..., None], -100)
            text_inputs = self.tokenizer(text, **output_kwargs["text_kwargs"])
            data.update(text_inputs)

        if audio is not None:
            audio_inputs = self.feature_extractor(audio, **output_kwargs.get("audio_kwargs", {}))
            data["input_features"] = audio_inputs["input_features"]

        return BatchFeature(
            data=data,
            tensor_type="pt" if cached_inputs else kwargs.get("return_tensors"),
        )

    def _build_synthesis_text(self, text):
        return f"<|im_start|>assistant\n{text}<|im_end|>\n<|im_start|>assistant\n"

    def _process_chat_inputs(self, text, audio=None, output_labels=False, **kwargs):
        requires_backends(self, ["torch"])
        output_kwargs = self._merge_kwargs(
            Qwen3TTSProcessorKwargs, tokenizer_init_kwargs=self.tokenizer.init_kwargs, **kwargs
        )
        text_kwargs = output_kwargs["text_kwargs"]
        if text_kwargs.get("return_tensors") not in (None, "pt"):
            raise ValueError("Qwen3TTS conversation inputs require `return_tensors='pt'`.")
        text_kwargs["return_tensors"] = "pt"
        prompts = [text] if isinstance(text, str) else text
        synthesis, instructions = [], []
        for prompt in prompts:
            instruction = None
            if prompt.startswith("<|im_start|>user\n"):
                instruction, separator, prompt = prompt.partition("<|im_end|>\n")
                if not separator:
                    raise ValueError("The instruction prompt must end with `<|im_end|>\\n`.")
                instruction += separator
            synthesis.append(prompt.replace("<|audio|>", ""))
            instructions.append(instruction)

        if output_labels:
            if audio is None or getattr(self, "audio_tokenizer", None) is None:
                raise ValueError("Conversation training requires target audio and an audio tokenizer.")
            if text_kwargs.get("truncation") not in (None, False, "do_not_truncate"):
                raise ValueError("Training text cannot be truncated because its prompt suffix is required.")
            text_kwargs.setdefault("padding", True)
            text_kwargs["return_attention_mask"] = True
            data = dict(self.tokenizer(synthesis, **text_kwargs))
        else:
            data = {
                "input_ids": [self.tokenizer(prompt, **text_kwargs)["input_ids"] for prompt in synthesis],
            }
            if any(instruction is not None for instruction in instructions):
                data["instruct_ids"] = [
                    self.tokenizer(instruction, **text_kwargs)["input_ids"] if instruction is not None else None
                    for instruction in instructions
                ]

        if audio is not None:
            if len(audio) != len(prompts):
                raise ValueError("Provide exactly one audio clip per conversation in an audio batch.")
            # Extract each unpadded clip independently: padding the waveform would change its mel features.
            audio_kwargs = output_kwargs["audio_kwargs"]
            audio_kwargs["return_tensors"] = None
            features = self.feature_extractor(audio, **audio_kwargs)["input_features"]
            features = [torch.as_tensor(feature, dtype=torch.float32) for feature in features]
            data["input_features"] = torch.nn.utils.rnn.pad_sequence(features, batch_first=True)
            lengths = torch.tensor([feature.shape[0] for feature in features])
            data["feature_attention_mask"] = (
                torch.arange(data["input_features"].shape[1])[None, :] < lengths[:, None]
            ).long()

            if output_labels:
                sampling_rate = audio_kwargs.get("sampling_rate", self.feature_extractor.sampling_rate)
                if sampling_rate != self.audio_tokenizer.config.input_sampling_rate:
                    raise ValueError(
                        "The audio tokenizer and speaker feature extractor must use the same sampling rate."
                    )
                codes = []
                with torch.no_grad():
                    for waveform in audio:
                        waveform = torch.as_tensor(
                            waveform, device=self.audio_tokenizer.device, dtype=self.audio_tokenizer.dtype
                        )[None, None]
                        # Encode without batch padding to preserve the codec's exact frame-length semantics.
                        encoded = self.audio_tokenizer.encode(waveform, return_dict=True).audio_codes[0]
                        codes.append(encoded.cpu().long())
                data["audio_codes"] = torch.nn.utils.rnn.pad_sequence(codes, batch_first=True)
                lengths = torch.tensor([code.shape[0] for code in codes])
                data["audio_attention_mask"] = (
                    torch.arange(data["audio_codes"].shape[1])[None, :] < lengths[:, None]
                ).long()
                data["labels"] = data["audio_codes"].clone()
                data["labels"].masked_fill_(~data["audio_attention_mask"].bool()[..., None], -100)
        return BatchFeature(data=data)

    def apply_chat_template(
        self,
        conversation,
        chat_template=None,
        tools=None,
        documents=None,
        add_generation_prompt=False,
        continue_final_message=False,
        return_assistant_tokens_mask=False,
        tokenize=None,
        return_tensors=None,
        return_dict=None,
        load_audio_from_video=False,
        processor_kwargs=None,
        **kwargs,
    ):
        """
        Format synthesis conversations, optionally loading a reference (or training target) audio clip.

        A `user` message supplies synthesis text and optionally one standard audio content block. `system` and
        `scene` messages supply voice instructions. User-message `language` and `speaker` select the language and
        preset speaker. With `processor_kwargs={"output_labels": True}`, the audio is both the training target and
        speaker reference; returned text, features, codes, masks, and labels are padded PyTorch tensors.

        Explicit `tokenize=False` returns the rendered Jinja prompt. Calls without `tokenize` preserve the
        generation-ready [`BatchFeature`] interface. Use `tokenize=True, return_dict=True` for model inputs.
        """
        legacy = tokenize is None
        tokenize = True if legacy else tokenize
        processor_kwargs = dict(processor_kwargs or {})
        if tokenize:
            conversations = [conversation] if isinstance(conversation[0], dict) else conversation
            audio_counts = [
                sum(
                    part.get("type") == "audio"
                    for message in messages
                    if not isinstance(message["content"], str)
                    for part in message["content"]
                )
                for messages in conversations
            ]
            if any(audio_counts) and any(count != 1 for count in audio_counts):
                raise ValueError("Provide exactly one audio clip per conversation in an audio batch.")
            for messages in conversations:
                if not any(message["role"] == "user" for message in messages):
                    raise ValueError("Each conversation must contain a `user` message with the text to synthesize.")
                for message in messages:
                    if message["role"] not in ("system", "scene", "user"):
                        raise ValueError(f"Unsupported message role for Qwen3TTS: {message['role']!r}")
            # Keep flat processing kwargs from replacing the nested kwargs (and the internal dispatch flag)
            # in ProcessorMixin. Variables declared by the Jinja template still belong to the renderer.
            template = chat_template if chat_template is not None else self.chat_template
            if isinstance(self.chat_template, dict):
                template = self.chat_template.get(chat_template or "default", chat_template)
            if template is not None:
                template_variables = _get_template_variables(template)
                for key in tuple(kwargs):
                    if key not in template_variables:
                        processor_kwargs[key] = kwargs.pop(key)
            processor_kwargs["_chat_template"] = True
        data = super().apply_chat_template(
            conversation,
            chat_template=chat_template,
            tools=tools,
            documents=documents,
            add_generation_prompt=add_generation_prompt,
            continue_final_message=continue_final_message,
            return_assistant_tokens_mask=return_assistant_tokens_mask,
            return_tensors=return_tensors,
            load_audio_from_video=load_audio_from_video,
            tokenize=tokenize,
            return_dict=True,
            processor_kwargs=processor_kwargs,
            **kwargs,
        )
        if not tokenize:
            return data
        if not processor_kwargs.get("output_labels"):
            languages, speakers = [], []
            for messages in conversations:
                users = [message for message in messages if message["role"] == "user"]
                language, speaker = "auto", None
                for message in users:
                    language = message.get("language", language)
                    speaker = message.get("speaker", speaker)
                languages.append(language)
                speakers.append(speaker)
            data["languages"] = languages
            data["speakers"] = speakers
        return data if legacy or return_dict else data["input_ids"]

    def decode(self, audio_codes):
        """
        Decode generated audio codes into audio waveforms using the audio tokenizer.

        Args:
            audio_codes (`torch.Tensor` or `list[torch.Tensor]`):
                The audio codes returned by [`Qwen3TTSForConditionalGeneration.generate`]. Either a single sequence of
                shape `(codes_length, num_quantizers)`, a list of such tensors (one per sample), or a single batched
                tensor of shape `(batch_size, codes_length, num_quantizers)`.

        Returns:
            `torch.Tensor` or `list[torch.Tensor]`: A single decoded waveform when a single sequence is passed,
            otherwise a list of waveforms, one per sample.
        """
        is_batched = isinstance(audio_codes, (list, tuple)) or (
            isinstance(audio_codes, torch.Tensor) and audio_codes.dim() == 3
        )
        if isinstance(audio_codes, torch.Tensor) and audio_codes.dim() == 3:
            audio_codes = list(audio_codes)
        elif not is_batched:
            audio_codes = [audio_codes]

        audios = []
        with torch.no_grad():
            for codes in audio_codes:
                codes = codes.unsqueeze(0).to(self.audio_tokenizer.device)
                audios.append(self.audio_tokenizer.decode(codes, return_dict=True).audio_values[0])
        return audios if is_batched else audios[0]

    def save_audio(
        self,
        audio: AudioInput,
        saving_path: str | Path | list[str | Path],
        **kwargs: Unpack[Qwen3TTSProcessorKwargs],
    ):
        if not is_soundfile_available():
            raise ImportError("Please install `soundfile` to save audio files.")

        audio = make_list_of_audio(audio)

        if isinstance(saving_path, (str, Path)):
            saving_path = [saving_path]
        elif not (isinstance(saving_path, (list, tuple)) and all(isinstance(p, (str, Path)) for p in saving_path)):
            raise ValueError("Invalid input path. Please provide a string, or a list of strings")

        if len(audio) != len(saving_path):
            raise ValueError("The number of audio and saving paths must be the same")

        sampling_rate = self.audio_tokenizer.config.output_sampling_rate
        for audio_value, p in zip(audio, saving_path):
            if isinstance(audio_value, torch.Tensor):
                audio_value = audio_value.cpu().float().numpy()
            sf.write(p, audio_value, sampling_rate)

    @property
    def model_input_names(self):
        tokenizer_input_names = self.tokenizer.model_input_names
        feature_extractor_input_names = self.feature_extractor.model_input_names
        return list(
            dict.fromkeys(
                tokenizer_input_names
                + feature_extractor_input_names
                + ["feature_attention_mask", "audio_codes", "audio_attention_mask", "speaker_embeddings"]
            )
        )


