import torch

from ...generation import GenerationMixin, LogitsProcessor, LogitsProcessorList


class BolmoLogitsProcessor(LogitsProcessor):
    r"""
    Bolmo predicts bytes, and a byte id shifted by `boundary_offset` means "this byte closes a patch". This processor:

    1. forces the first generated byte to be the last prompt byte (which the model only re-reads to decide whether it
       closes a patch, since boundaries need one byte of lookahead),
    2. makes rows that reached a patch boundary emit `bpe_token_end_id` until every row has, so the global model only
       ever runs on full batches.
    """

    def __init__(
        self,
        last_prompt_bytes: torch.LongTensor,
        prompt_length: int,
        boundary_offset: int,
        bpe_token_end_id: int,
        pad_token_id: int,
    ):
        self.allowed_first_bytes = torch.stack([last_prompt_bytes, last_prompt_bytes + boundary_offset], dim=-1)
        self.prompt_length = prompt_length
        self.boundary_offset = boundary_offset
        self.bpe_token_end_id = bpe_token_end_id
        self.wait_ids = torch.tensor([bpe_token_end_id, pad_token_id])

    def __call__(self, input_ids: torch.LongTensor, scores: torch.FloatTensor) -> torch.FloatTensor:
        if input_ids.shape[1] == self.prompt_length:
            # rows are repeated `num_beams` / `num_return_sequences` times by `generate`
            repeats = scores.shape[0] // self.allowed_first_bytes.shape[0]
            allowed = self.allowed_first_bytes.repeat_interleave(repeats, dim=0).to(scores.device)
            return torch.full_like(scores, -float("inf")).scatter(1, allowed, scores.gather(1, allowed))

        last_token = input_ids[:, -1]
        at_boundary = (last_token >= self.boundary_offset) | torch.isin(
            last_token, self.wait_ids.to(last_token.device)
        )
        if at_boundary.all():
            return scores
        scores = scores.masked_fill(at_boundary[:, None], -float("inf"))
        scores[at_boundary, self.bpe_token_end_id] = 0
        return scores


class BolmoGenerationMixin(GenerationMixin):
    def prepare_inputs_for_generation(self, input_ids, expand_byte_ids=None, is_first_iteration=False, **kwargs):
        model_inputs = super().prepare_inputs_for_generation(
            input_ids, is_first_iteration=is_first_iteration, **kwargs
        )
        # patch positions are tracked by the cache, byte positions are meaningless to the global model
        model_inputs.pop("position_ids", None)
        if not is_first_iteration:
            model_inputs["boundary_mask"] = None
            model_inputs["expanded_input_ids"] = torch.tensor(
                [expand_byte_ids(row, n_last=1) for row in input_ids.tolist()], device=input_ids.device
            )
        return model_inputs

    def generate(
        self,
        input_ids: torch.LongTensor,
        expanded_input_ids: torch.LongTensor,
        tokenizer=None,
        attention_mask: torch.LongTensor | None = None,
        logits_processor: LogitsProcessorList | None = None,
        **kwargs,
    ):
        r"""
        Same as [`~GenerationMixin.generate`], but `tokenizer` (a [`BolmoTokenizer`]) is required: every new byte needs
        its subword expansion. Returned ids contain boundary-fused bytes and `<bpe_token_end>` markers, which
        `tokenizer.decode(..., skip_special_tokens=True)` removes.
        """
        if tokenizer is None:
            raise ValueError("Bolmo needs `tokenizer=` in `generate` to expand generated bytes into subword ids.")
        boundary_offset = self.config.vocab_size // 2
        boundary_mask = self.model.predict_boundaries(input_ids, expanded_input_ids, attention_mask)
        bolmo_processor = BolmoLogitsProcessor(
            last_prompt_bytes=input_ids[:, -1],
            prompt_length=input_ids.shape[1] - 1,
            boundary_offset=boundary_offset,
            bpe_token_end_id=self.config.bpe_token_end_id,
            pad_token_id=self.config.pad_token_id,
        )
        eos_token_id = self.config.eos_token_id
        kwargs.setdefault("eos_token_id", [eos_token_id, eos_token_id + boundary_offset])
        return super().generate(
            input_ids[:, :-1],
            attention_mask=attention_mask[:, :-1] if attention_mask is not None else None,
            expanded_input_ids=expanded_input_ids[:, :-1],
            boundary_mask=boundary_mask[:, :-1],
            logits_processor=LogitsProcessorList([*(logits_processor or []), bolmo_processor]),
            expand_byte_ids=tokenizer.expand_byte_ids,
            tokenizer=tokenizer,
            **kwargs,
        )
