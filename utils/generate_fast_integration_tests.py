#!/usr/bin/env python3
"""Generate tests/test_fast_integration.py from the latest fleet manifest.

Usage (inside the CI container after `uv pip install -e .` and transformers-ci):
    python utils/generate_fast_integration_tests.py

Calls resolve_revision() to get the current fleet revision, downloads the control
and prototypes fleet lock files, enumerates all (fleet, contract, target, variant)
tuples, and writes tests/test_fast_integration.py.
"""

import json
from pathlib import Path


# Variants run per fleet — mirrors pr-ci_contracts.yml
FLEET_VARIANTS = {
    "control": ["default", "bfloat16"],
    "prototypes": ["bfloat16"],
}


def short(repo: str) -> str:
    return repo.split("/")[-1]


def enumerate_params(fleet_name: str, lock: dict) -> list:
    """Return [(fleet, contract_name, target, variant)] from a fleet lock dict."""
    params = []
    for contract_name, contract in lock["contracts"].items():
        for repo, pin in contract.get("fixtures", {}).items():
            target = pin.get("target", short(repo))
            for variant in FLEET_VARIANTS[fleet_name]:
                params.append((fleet_name, contract_name, target, variant))
    return params


def load_lock(fleet_name: str, revision: str) -> dict:
    from transformersci.contracts.fleet import lock_path

    path, _ = lock_path(fleet_name, revision)
    return json.loads(Path(path).read_text(encoding="utf-8"))


TEMPLATE = '''\
# This file is generated by utils/generate_fast_integration_tests.py — do not edit by hand.
# Re-generate with: python utils/generate_fast_integration_tests.py

"""Fast integration tests: one pytest item per model contract check.

The session fixture runs each fleet+variant exactly as the original workflow
(no --contract/--target), so results match the old non-pytest CI behaviour.
Individual pytest items then assert against the collected results.

Run all:
    pytest tests/test_fast_integration.py -v

Run one model:
    pytest tests/test_fast_integration.py -v -k SmolLM
"""

import json
from pathlib import Path

import pytest

from transformersci.contracts import run as _run


FLEET_REVISION = "{revision}"
FLEET_VARIANTS = {fleet_variants}
PARAMS = {params}


@pytest.fixture(scope="session")
def fleet_results():
    """Run each fleet+variant once (full fleet, no --contract/--target) and collect results."""
    results = {{}}
    for fleet_name, variants in FLEET_VARIANTS.items():
        for variant in variants:
            output = Path(f"/tmp/mic-{{fleet_name}}-{{variant}}.jsonl")
            output.unlink(missing_ok=True)
            _run.main([
                "--fixtures-only",
                "--run-all",
                "--fleet", fleet_name,
                "--fleet-revision", FLEET_REVISION,
                "--variant", variant,
                "--output", str(output),
            ])
            if output.exists():
                for line in output.read_text(encoding="utf-8").splitlines():
                    if line.strip():
                        r = json.loads(line)
                        key = (fleet_name, r.get("target", ""), variant)
                        results[key] = r
    return results


@pytest.mark.parametrize("fleet,contract,target,variant", PARAMS)
def test_contract(fleet, contract, target, variant, fleet_results):
    r = fleet_results.get((fleet, target, variant))
    assert r is not None, f"no result for {{fleet}}/{{target}}[{{variant}}]"
    if r["status"] == "unsupported":
        reason = r["failures"][0] if r.get("failures") else "unsupported on this platform"
        pytest.skip(reason)
    assert r["status"] == "pass", "\\n".join(r.get("failures", [str(r)]))
'''


def main():
    from transformersci.contracts.fleet import resolve_revision

    repo_root = Path(__file__).parent.parent
    output_path = repo_root / "tests" / "test_fast_integration.py"

    revision = resolve_revision()
    print(f"Fleet revision: {revision}")

    all_params = []
    for fleet_name in FLEET_VARIANTS:
        print(f"Loading {fleet_name} fleet...")
        lock = load_lock(fleet_name, revision)
        params = enumerate_params(fleet_name, lock)
        print(f"  {len(params)} params")
        all_params.extend(params)

    all_params.sort()
    print(f"Total: {len(all_params)} test items")

    params_repr = "[\n"
    for item in all_params:
        params_repr += f"    {item!r},\n"
    params_repr += "]"

    content = (
        TEMPLATE.replace("{revision}", revision)
        .replace("{fleet_variants}", repr(FLEET_VARIANTS))
        .replace("{params}", params_repr)
    )
    output_path.write_text(content, encoding="utf-8")
    print(f"Written: {output_path}")


if __name__ == "__main__":
    main()
