    def test_new_init_inherits_module_license(self):
        with tempfile.TemporaryDirectory() as tmp:
            model = Path(tmp)
            header = "# Copyright 2026 Model authors.\n"
            (model / "configuration_example.py").write_text(header + "__all__ = []\n", encoding="utf-8")
            self.assertEqual(check_inits.get_license_header(model / "__init__.py", ["configuration_example"]), header)
