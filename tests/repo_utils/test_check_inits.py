            init.write_text(license_header + "\n", encoding="utf-8")

            with patch.object(check_inits, "REPO_ROOT", root), patch.object(check_inits, "MODELS_PATH", models):
                kwargs = {
                    "init_path": init,
                    "import_lines": ["from .configuration_example import *"],
                    "module_names": ["configuration_example"],
                }
                generated = check_inits.generate_init(**kwargs)

